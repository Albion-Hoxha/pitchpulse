"""Statistician: turns the raw event stream into live match statistics.

Deterministic on purpose — every number the AI agents later say on air is
checked against these figures, so they must never be generated by an LLM.
"""
from collections import deque

MOMENTUM_WINDOW = 5 * 60  # seconds
FINAL_THIRD_X = 70.0
HALF_SECONDS = 45 * 60
# Chaos index across 50 simulated matches: median ~28, 10th/90th percentiles ~22/35.
CHAOS_LEVEL, CONTROL_LEVEL = 35, 22


def pass_difficulty(e):
    """1–10 rating: longer, pressured and final-third passes are harder."""
    score = 1 + e["length"] / 6 + (2 if e.get("under_pressure") else 0) + (2 if e["end_x"] > 88 else 0)
    return round(min(score, 10), 1)


def _blank():
    return {"goals": 0, "shots": 0, "on_target": 0, "xg": 0.0, "passes": 0, "passes_completed": 0,
            "final_third_passes": 0, "pressures": 0, "tackles": 0, "interceptions": 0,
            "possession_seconds": 0.0, "top_shot_kmh": 0.0, "difficulty_sum": 0.0}


class MatchStats:
    def __init__(self):
        self.team = {"home": _blank(), "away": _blank()}
        self.halves = {p: {"home": _blank(), "away": _blank()} for p in (1, 2)}  # same counters, per half
        self.players = {}  # name -> {"team", "passes", "passes_completed", "shots", "xg", "goals"}
        self.recent = deque()  # (t, side, threat) inside the momentum window
        self.flow_events = deque()  # (t, side, kind, ok) inside the same window, for control vs chaos
        self.period_start = 0.0
        self.last_t, self.last_poss = 0.0, "home"
        self.clock, self.period = "0:00", 1

    def _player(self, side, name):
        return self.players.setdefault(name, {"team": side, "passes": 0, "passes_completed": 0,
                                              "shots": 0, "xg": 0.0, "goals": 0})

    def update(self, e):
        """Fold one event into the running totals and return it, enriched where useful."""
        if e["type"] not in ("half_time", "full_time"):  # time since the last event belongs to its half
            held = max(e["t"] - self.last_t, 0)
            for t in (self.team, self.halves[self.period]):
                t[self.last_poss]["possession_seconds"] += held
        self.last_t, self.last_poss = e["t"], e["possession"]
        self.clock, self.period = e["clock"], e["period"]
        side, kind = e["team"], e["type"]
        counters = (self.team[side], self.halves[self.period][side])
        threat = 0.0

        def bump(key, amount=1):
            for c in counters:
                c[key] += amount

        if kind == "pass":
            p = self._player(side, e["player"])
            bump("passes")
            p["passes"] += 1
            e["difficulty"] = pass_difficulty(e)
            bump("difficulty_sum", e["difficulty"])
            if e["outcome"] == "complete":
                bump("passes_completed")
                p["passes_completed"] += 1
                if e["end_x"] > FINAL_THIRD_X:
                    bump("final_third_passes")
                    threat = 0.02
        elif kind == "shot":
            p = self._player(side, e["player"])
            bump("shots")
            bump("xg", e["xg"])
            p["shots"] += 1
            p["xg"] += e["xg"]
            for c in counters:
                c["top_shot_kmh"] = max(c["top_shot_kmh"], e["speed_kmh"])
            if e["outcome"] in ("goal", "saved"):
                bump("on_target")
            if e["outcome"] == "goal":
                bump("goals")
                p["goals"] += 1
            threat = e["xg"]
        elif kind == "pressure":
            bump("pressures")
        elif kind == "tackle":
            bump("tackles")
        elif kind == "interception":
            bump("interceptions")

        if kind == "half_time":  # the 2nd-half clock restarts at 45:00, so rolling windows start afresh
            self.recent.clear()
            self.flow_events.clear()
            self.period_start = HALF_SECONDS
        if threat:
            self.recent.append((e["t"], side, threat))
        if kind in ("pass", "tackle", "interception", "pressure"):
            self.flow_events.append((e["t"], side, kind, e.get("outcome") != "incomplete"))
        for window in (self.recent, self.flow_events):
            while window and window[0][0] < e["t"] - MOMENTUM_WINDOW:
                window.popleft()
        return e

    def flow(self):
        """Control vs chaos over the last 5 minutes: how often the ball changes hands compared
        with completed passes, the game's tempo, and how hard each side is pressing."""
        minutes = max(min(self.last_t - self.period_start, MOMENTUM_WINDOW), 60) / 60
        completed = sum(1 for _, _, k, ok in self.flow_events if k == "pass" and ok)
        turnovers = sum(1 for _, _, k, _ in self.flow_events if k in ("tackle", "interception"))
        passes = sum(1 for _, _, k, _ in self.flow_events if k == "pass")
        chaos = round(100 * turnovers / (completed + turnovers)) if completed + turnovers else 0
        state = "chaos" if chaos >= CHAOS_LEVEL else "control" if chaos <= CONTROL_LEVEL else "balanced"
        per_side = lambda kind, ok=None: {s: sum(1 for _, side, k, good in self.flow_events
                                                 if k == kind and side == s and ok in (None, good))
                                          for s in ("home", "away")}
        press = {s: round(n / minutes, 1) for s, n in per_side("pressure").items()}
        return {"chaos": chaos, "state": state, "tempo_ppm": round(passes / minutes, 1), "press_per_min": press,
                "completed_passes": per_side("pass", True)}

    def momentum(self):
        """-100 (away dominating) .. +100 (home dominating) over the last 5 minutes."""
        h = sum(v for _, side, v in self.recent if side == "home")
        a = sum(v for _, side, v in self.recent if side == "away")
        return 0 if h + a == 0 else round(100 * (h - a) / (h + a))

    def snapshot(self):
        return {"clock": self.clock, "period": self.period, "momentum": self.momentum(), "flow": self.flow(),
                "teams": _summary(self.team)}

    def by_half(self):
        """The same team stats for each half played so far (keys "first_half", "second_half")."""
        out = {"first_half": _summary(self.halves[1])}
        if self.period == 2:
            out["second_half"] = _summary(self.halves[2])
        return out


def _summary(team):
    total = sum(t["possession_seconds"] for t in team.values()) or 1
    return {side: {
        "goals": t["goals"], "shots": t["shots"], "on_target": t["on_target"],
        "xg": round(t["xg"], 2),
        "possession_pct": round(100 * t["possession_seconds"] / total),
        "passes": t["passes"],
        "pass_accuracy_pct": round(100 * t["passes_completed"] / t["passes"]) if t["passes"] else 0,
        "pass_difficulty_avg": round(t["difficulty_sum"] / t["passes"], 1) if t["passes"] else 0,
        "final_third_passes": t["final_third_passes"],
        "pressures": t["pressures"], "tackles": t["tackles"], "interceptions": t["interceptions"],
        "top_shot_kmh": t["top_shot_kmh"],
    } for side, t in team.items()}
